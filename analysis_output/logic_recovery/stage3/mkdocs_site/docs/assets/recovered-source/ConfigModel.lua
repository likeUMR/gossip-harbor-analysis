function ConfigModel:GetReplacesFilePath(path, separator)
  local fileName = path
  local lastSepIndex = StringUtil.rFindChar(path, separator or "/")
  if lastSepIndex ~= nil then
    fileName = string.sub(path, lastSepIndex + 1)
  end
  local config = self:GetServerConfig(ServerConfigKey.FileReplace)
  if config then
    for i = 1, #config do
      if config[i].file == fileName then
        return path .. config[i].suffix
      end
    end
  end
  return path
end

