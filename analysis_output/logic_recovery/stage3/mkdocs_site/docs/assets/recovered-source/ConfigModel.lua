function ConfigModel:_UpdateGeneralConfigInfo()
  self.m_generalConfigs = {}
  local serverConfig = self:GetServerConfig(ServerConfigKey.GeneralConf)
  if Table.IsEmpty(serverConfig) then
    return nil
  end
  for _, v in pairs(serverConfig) do
    self.m_generalConfigs[v.confType] = v
  end
  if GameConfig.IsTestMode() and GM and GM.TestModel then
    GM.TestModel:CustomizeGeneralConfigs()
  end
end

function ConfigModel:LoadDynamicConfigAsync(requireStr, callback, resultCustomFunc)
  local fileReplaceRequire = self:GetReplacesFilePath(requireStr, ".")
  if not self.m_cacheConfigRawFile then
    self.m_cacheConfigRawFile = {}
  end
  if self.m_cacheConfigRawFile[fileReplaceRequire] then
    callback(self.m_cacheConfigRawFile[fileReplaceRequire])
    return
  end
  
  local function loadedCallback(tb, reqStr)
    if resultCustomFunc then
      self.m_cacheConfigRawFile[reqStr] = resultCustomFunc(tb)
    else
      self.m_cacheConfigRawFile[reqStr] = tb
    end
    if callback then
      callback(self.m_cacheConfigRawFile[reqStr])
    end
  end
  
  LuaManager:LoadDynamicConfigAsync(fileReplaceRequire, function(tb)
    if not tb then
      LuaManager:LoadDynamicConfigAsync(requireStr, function(tb)
        if not tb then
          GM.BIManager:LogErrorInfo("tm_ld_er", requireStr .. "\n" .. debug.traceback())
          CS.CSErrorMonitor.OpenForceRestartWindow("force_restart_desc")
          return
        end
        loadedCallback(tb, requireStr)
      end)
      return
    end
    loadedCallback(tb, fileReplaceRequire)
  end)
end

